"""Generate the zeile application icon set (scalable SVG + hicolor PNG sizes).

The icon combines the erdlabs label mark (``brand/logo/logo.svg`` -- the flat
two-colour vector master) with a text-line / caret motif: ``zeile`` is German
for "line", so the app is drawn as a line of text with a blinking cursor under
the mark.

Colours are read from the *generated* token file ``brand/colors/palette.json``
(produced there by ``scripts/build-colors.sh``). No hex literal is written in
this script or anywhere else in application code.

Outputs, all inside the repository root:

    assets/zeile.svg                     app icon (kept byte-identical below)
    icons/hicolor/scalable/apps/zeile.svg
    icons/hicolor/<size>x<size>/apps/zeile.png  sizes 16 24 32 48 64 128 256 512

Directory names follow the freedesktop hicolor layout (``48x48/apps``):
GtkIconTheme only searches the directories listed in the theme's
``index.theme``, which lists ``<size>x<size>`` names -- a bare ``48/apps``
directory is silently ignored.

Sizes below 48 px carry the caret motif only: BRAND.md section 5 sets 48 px
as the minimum size for the mark on its own ("below that it turns to mush"),
so the small sizes drop the mark instead of shipping a smudge.

Requires ``rsvg-convert`` (librsvg) on PATH. Re-run after any brand change:

    python3 scripts/build_icons.py
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

ICON_NAME = "zeile"
CANVAS = 512
PNG_SIZES = (16, 24, 32, 48, 64, 128, 256, 512)

# Bounding box of the mark inside brand/logo/logo.svg's own 1024-unit user
# space, measured once by rasterising the master (2026-10-25) and reading the
# alpha bbox. Used to place the mark precisely without a round trip per run.
MARK_BBOX = (232.0, 82.0, 792.0, 908.0)  # x0, y0, x1, y1 in logo.svg units
MARK_TOP = 44.0  # where the mark starts on the 512 canvas
MARK_HEIGHT = 290.0

# Text-line motif on the 512 canvas (y positions are top edges).
BAR_HEIGHT = 26.0
BAR_X = 72.0
BAR_WIDTH = 368.0
BAR_1_Y = 354.0
BAR_2_Y = 396.0
CARET_X, CARET_Y, CARET_W, CARET_H = 72.0, 441.0, 26.0, 38.0
BAR_3_X, BAR_3_Y, BAR_3_WIDTH = 114.0, 447.0, 200.0

# Caret-only variant for the sub-48 px sizes (thick enough to survive 16 px).
STEM_X, STEM_Y, STEM_W, STEM_H = 216.0, 88.0, 80.0, 336.0
TICK_X, TICK_W, TICK_H = 144.0, 224.0, 56.0
TICK_BOTTOM_Y = STEM_Y + STEM_H - TICK_H

PNG_MAGIC = b"\x89PNG\r\n\x1a\n"

_HEADER = (
    "<!-- Generated by scripts/build_icons.py. Do not edit by hand;"
    " colours come from brand/colors/palette.json. -->"
)


def _num(value: float) -> str:
    """Compact fixed-point formatting for SVG attributes."""
    return f"{value:.3f}".rstrip("0").rstrip(".")


def load_palette(brand_dir: Path) -> dict[str, str]:
    """Read the generated colour token file; returns {token: hex}."""
    palette_file = brand_dir / "colors" / "palette.json"
    data = json.loads(palette_file.read_text(encoding="utf-8"))
    tokens = {key: value["hex"] for key, value in data.items() if isinstance(value, dict)}
    required = ("canvas", "slate", "copper")
    missing = [name for name in required if name not in tokens]
    if missing:
        raise SystemExit(f"{palette_file}: missing tokens: {', '.join(missing)}")
    return tokens


def mark_group(brand_dir: Path) -> str:
    """The label mark, positioned on the 512 canvas, as one <g> element."""
    logo_file = brand_dir / "logo" / "logo.svg"
    text = logo_file.read_text(encoding="utf-8")
    inner = text[text.index(">", text.index("<svg")) + 1 : text.rindex("</svg>")]
    inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.DOTALL).strip()

    x0, y0, x1, y1 = MARK_BBOX
    scale = MARK_HEIGHT / (y1 - y0)
    width = (x1 - x0) * scale
    left = (CANVAS - width) / 2.0
    tx = left - x0 * scale
    ty = MARK_TOP - y0 * scale
    indent = "\n".join(f"    {line}" for line in inner.splitlines())
    return (
        f'  <g transform="translate({_num(tx)} {_num(ty)}) '
        f'scale({_num(scale)})">\n{indent}\n  </g>'
    )


def build_svg(tokens: dict[str, str], mark: str | None) -> str:
    """Full design (mark + line motif) when mark is given, caret-only below."""
    ground = f'  <rect width="{CANVAS}" height="{CANVAS}" fill="{tokens["canvas"]}"/>'
    if mark is None:
        motif = "\n".join(
            [
                f'  <rect x="{_num(TICK_X)}" y="{_num(STEM_Y)}" '
                f'width="{_num(TICK_W)}" height="{_num(TICK_H)}" '
                f'rx="16" fill="{tokens["copper"]}"/>',
                f'  <rect x="{_num(STEM_X)}" y="{_num(STEM_Y)}" '
                f'width="{_num(STEM_W)}" height="{_num(STEM_H)}" '
                f'rx="16" fill="{tokens["copper"]}"/>',
                f'  <rect x="{_num(TICK_X)}" y="{_num(TICK_BOTTOM_Y)}" '
                f'width="{_num(TICK_W)}" height="{_num(TICK_H)}" '
                f'rx="16" fill="{tokens["copper"]}"/>',
            ]
        )
        body = f"{ground}\n{motif}"
    else:
        bars = "\n".join(
            [
                f'  <rect x="{_num(BAR_X)}" y="{_num(BAR_1_Y)}" '
                f'width="{_num(BAR_WIDTH)}" height="{_num(BAR_HEIGHT)}" '
                f'rx="{_num(BAR_HEIGHT / 2)}" fill="{tokens["slate"]}"/>',
                f'  <rect x="{_num(BAR_X)}" y="{_num(BAR_2_Y)}" '
                f'width="{_num(BAR_WIDTH)}" height="{_num(BAR_HEIGHT)}" '
                f'rx="{_num(BAR_HEIGHT / 2)}" fill="{tokens["slate"]}"/>',
                f'  <rect x="{_num(CARET_X)}" y="{_num(CARET_Y)}" '
                f'width="{_num(CARET_W)}" height="{_num(CARET_H)}" '
                f'rx="6" fill="{tokens["copper"]}"/>',
                f'  <rect x="{_num(BAR_3_X)}" y="{_num(BAR_3_Y)}" '
                f'width="{_num(BAR_3_WIDTH)}" height="{_num(BAR_HEIGHT)}" '
                f'rx="{_num(BAR_HEIGHT / 2)}" fill="{tokens["slate"]}"/>',
            ]
        )
        body = f"{ground}\n{mark}\n{bars}"

    return (
        '<svg xmlns="http://www.w3.org/2000/svg" '
        f'viewBox="0 0 {CANVAS} {CANVAS}" width="{CANVAS}" height="{CANVAS}" '
        'role="img" aria-label="zeile">\n'
        "  <title>zeile</title>\n"
        f"{_HEADER}\n"
        f"{body}\n"
        "</svg>\n"
    )


def render_png(svg_text: str, size: int, dest: Path) -> None:
    """Rasterise one square PNG and verify its signature on the way out."""
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as handle:
        handle.write(svg_text)
        tmp = Path(handle.name)
    try:
        subprocess.run(
            [
                "rsvg-convert",
                "--format",
                "png",
                "--width",
                str(size),
                "--height",
                str(size),
                "--output",
                str(dest),
                str(tmp),
            ],
            check=True,
            capture_output=True,
        )
    finally:
        tmp.unlink(missing_ok=True)
    header = dest.read_bytes()[:8]
    if header != PNG_MAGIC:
        raise SystemExit(f"{dest}: bad PNG header {header.hex()}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--brand-dir",
        type=Path,
        default=Path(
            os.environ.get(
                "ERDLABS_BRAND_DIR", str(Path.home() / "projects/business/erdlabs/brand")
            )
        ),
        help="path to the erdlabs brand directory (default: %(default)s)",
    )
    args = parser.parse_args(argv)

    if shutil.which("rsvg-convert") is None:
        raise SystemExit("rsvg-convert not found on PATH (install librsvg)")

    tokens = load_palette(args.brand_dir)
    mark = mark_group(args.brand_dir)
    full_svg = build_svg(tokens, mark)
    small_svg = build_svg(tokens, mark=None)

    written: list[Path] = []
    for dest in (
        REPO / "assets" / "zeile.svg",
        REPO / "icons" / "hicolor" / "scalable" / "apps" / "zeile.svg",
    ):
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(full_svg, encoding="utf-8")
        written.append(dest)

    for size in PNG_SIZES:
        source = small_svg if size < 48 else full_svg
        dest = REPO / "icons" / "hicolor" / f"{size}x{size}" / "apps" / "zeile.png"
        dest.parent.mkdir(parents=True, exist_ok=True)
        render_png(source, size, dest)
        written.append(dest)

    for path in written:
        print(f"wrote {path.relative_to(REPO)} ({path.stat().st_size} bytes)")
    print(f"palette: {args.brand_dir / 'colors' / 'palette.json'}")
    print(f"mark:    {args.brand_dir / 'logo' / 'logo.svg'}")
    print("PNG header check: all 8 files start with 89 50 4e 47")
    return 0


if __name__ == "__main__":
    sys.exit(main())
